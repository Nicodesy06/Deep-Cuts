-- Deep Cuts schema v1.
-- Conventions: ids are TEXT UUIDs (stable across path changes), timestamps are
-- unix milliseconds (INTEGER). Effective metadata is cached on `tracks`; the
-- provenance of every value lives in `track_fields`.

CREATE TABLE tracks (
    id              TEXT PRIMARY KEY,
    created_at      INTEGER NOT NULL,
    updated_at      INTEGER NOT NULL,
    -- effective (resolved) metadata, see track_fields for provenance
    title           TEXT,
    artist          TEXT,
    version         TEXT,
    remixer         TEXT,
    album           TEXT,
    album_artist    TEXT,
    label           TEXT,
    genre           TEXT,
    subgenre        TEXT,
    year            INTEGER,
    bpm             REAL,
    musical_key     TEXT,           -- as displayed (original notation)
    key_camelot     TEXT,           -- normalised Camelot code, e.g. '8A'
    comment         TEXT,
    isrc            TEXT,
    duration_ms     INTEGER,
    rating          INTEGER CHECK (rating BETWEEN 0 AND 5),
    favorite        INTEGER NOT NULL DEFAULT 0,
    notes           TEXT,
    has_artwork     INTEGER NOT NULL DEFAULT 0,
    lufs            REAL,           -- measured integrated loudness (analysis)
    preview_ms      INTEGER,        -- start of the measured highest-energy region
    analysis_status TEXT NOT NULL DEFAULT 'none' -- none|queued|done|failed
);
CREATE INDEX idx_tracks_artist ON tracks(artist COLLATE NOCASE);
CREATE INDEX idx_tracks_title ON tracks(title COLLATE NOCASE);
CREATE INDEX idx_tracks_bpm ON tracks(bpm);
CREATE INDEX idx_tracks_key ON tracks(key_camelot);
CREATE INDEX idx_tracks_genre ON tracks(genre COLLATE NOCASE);
CREATE INDEX idx_tracks_created ON tracks(created_at);

-- Every metadata value with its origin. source:
--   'file'       original tags read from the audio file
--   'import:<x>' imported from another library (e.g. import:rekordbox)
--   'analysis'   generated by Deep Cuts analysers
--   'user'       edited by the user (never overwritten automatically)
CREATE TABLE track_fields (
    track_id   TEXT NOT NULL REFERENCES tracks(id) ON DELETE CASCADE,
    field      TEXT NOT NULL,
    source     TEXT NOT NULL,
    value      TEXT,
    updated_at INTEGER NOT NULL,
    PRIMARY KEY (track_id, field, source)
);

CREATE TABLE files (
    id          TEXT PRIMARY KEY,
    track_id    TEXT NOT NULL REFERENCES tracks(id) ON DELETE CASCADE,
    path        TEXT NOT NULL UNIQUE,
    size        INTEGER NOT NULL,
    mtime_ms    INTEGER,
    quick_hash  TEXT,           -- blake3 over size + head + tail (fast identity)
    format      TEXT,
    codec       TEXT,
    bitrate     INTEGER,        -- kbps
    sample_rate INTEGER,
    bit_depth   INTEGER,
    channels    INTEGER,
    missing     INTEGER NOT NULL DEFAULT 0,
    last_seen   INTEGER NOT NULL,
    added_at    INTEGER NOT NULL
);
CREATE INDEX idx_files_track ON files(track_id);
CREATE INDEX idx_files_hash ON files(quick_hash);

CREATE TABLE external_ids (
    track_id    TEXT NOT NULL REFERENCES tracks(id) ON DELETE CASCADE,
    source      TEXT NOT NULL,
    external_id TEXT NOT NULL,
    PRIMARY KEY (source, external_id)
);
CREATE INDEX idx_external_track ON external_ids(track_id);

-- Keep / Pass / Maybe, per context. 'global' is the default context; a Pass
-- in a context (e.g. a taste profile or a set) is NOT a global exclusion.
CREATE TABLE decisions (
    track_id   TEXT NOT NULL REFERENCES tracks(id) ON DELETE CASCADE,
    context    TEXT NOT NULL DEFAULT 'global',
    decision   TEXT NOT NULL CHECK (decision IN ('keep','pass','maybe')),
    updated_at INTEGER NOT NULL,
    PRIMARY KEY (track_id, context)
);
CREATE INDEX idx_decisions_ctx ON decisions(context, decision);

CREATE TABLE tags (
    id        TEXT PRIMARY KEY,
    name      TEXT NOT NULL,
    category  TEXT NOT NULL DEFAULT 'custom',
    parent_id TEXT REFERENCES tags(id) ON DELETE SET NULL,
    UNIQUE (category, name)
);

CREATE TABLE track_tags (
    track_id      TEXT NOT NULL REFERENCES tracks(id) ON DELETE CASCADE,
    tag_id        TEXT NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
    origin        TEXT NOT NULL,             -- user|ai|import:<x>
    source_model  TEXT,
    model_version TEXT,
    confidence    REAL,                      -- only when calibrated
    status        TEXT NOT NULL DEFAULT 'confirmed', -- suggested|confirmed|rejected
    updated_at    INTEGER NOT NULL,
    PRIMARY KEY (track_id, tag_id, origin)
);

CREATE TABLE playlists (
    id         TEXT PRIMARY KEY,
    name       TEXT NOT NULL,
    parent_id  TEXT REFERENCES playlists(id) ON DELETE CASCADE,
    kind       TEXT NOT NULL DEFAULT 'manual', -- manual|smart|folder
    rules      TEXT,                           -- smart playlist query
    source     TEXT,                           -- e.g. import:rekordbox
    created_at INTEGER NOT NULL,
    updated_at INTEGER NOT NULL
);

CREATE TABLE playlist_tracks (
    playlist_id TEXT NOT NULL REFERENCES playlists(id) ON DELETE CASCADE,
    position    INTEGER NOT NULL,
    track_id    TEXT NOT NULL REFERENCES tracks(id) ON DELETE CASCADE,
    PRIMARY KEY (playlist_id, position)
);
CREATE INDEX idx_playlist_tracks_track ON playlist_tracks(track_id);

CREATE TABLE cue_points (
    id          TEXT PRIMARY KEY,
    track_id    TEXT NOT NULL REFERENCES tracks(id) ON DELETE CASCADE,
    kind        TEXT NOT NULL,    -- cue|hotcue|loop|memory|suggestion
    slot        INTEGER,          -- hot cue index (0 = A) when applicable
    start_ms    REAL NOT NULL,
    end_ms      REAL,             -- loops only
    name        TEXT,
    color       TEXT,
    source      TEXT NOT NULL,    -- user|import:<x>|analysis
    locked      INTEGER NOT NULL DEFAULT 0, -- confirmed by the user: never auto-modified
    created_at  INTEGER NOT NULL
);
CREATE INDEX idx_cues_track ON cue_points(track_id);

CREATE TABLE beatgrids (
    track_id   TEXT NOT NULL REFERENCES tracks(id) ON DELETE CASCADE,
    source     TEXT NOT NULL,
    bpm        REAL NOT NULL,
    first_beat_ms REAL NOT NULL,
    markers    TEXT,            -- JSON array for variable-tempo grids
    PRIMARY KEY (track_id, source)
);

-- Raw analyser output, versioned. Re-analysis is skipped when an equal
-- analyser version already analysed the same file content.
CREATE TABLE analysis_results (
    id               TEXT PRIMARY KEY,
    track_id         TEXT NOT NULL REFERENCES tracks(id) ON DELETE CASCADE,
    analyzer         TEXT NOT NULL,
    analyzer_version TEXT NOT NULL,
    file_hash        TEXT,
    created_at       INTEGER NOT NULL,
    duration_ms      INTEGER,     -- wall-clock analysis time
    results          TEXT NOT NULL -- JSON
);
CREATE INDEX idx_analysis_track ON analysis_results(track_id, analyzer, created_at);

CREATE TABLE waveforms (
    track_id   TEXT PRIMARY KEY REFERENCES tracks(id) ON DELETE CASCADE,
    version    INTEGER NOT NULL,
    bins       INTEGER NOT NULL,
    data       BLOB NOT NULL     -- per bin: peak u8, rms u8, low u8, high u8
);

-- Persistent job queue. Jobs left 'running' by a crashed process are
-- re-queued at the next startup (jobs::recover_interrupted).
CREATE TABLE jobs (
    id         INTEGER PRIMARY KEY AUTOINCREMENT,
    kind       TEXT NOT NULL,
    track_id   TEXT REFERENCES tracks(id) ON DELETE CASCADE,
    payload    TEXT,
    status     TEXT NOT NULL DEFAULT 'queued', -- queued|running|done|failed|cancelled
    priority   INTEGER NOT NULL DEFAULT 0,
    attempts   INTEGER NOT NULL DEFAULT 0,
    error      TEXT,
    owner      TEXT,              -- process that claimed the job
    created_at INTEGER NOT NULL,
    updated_at INTEGER NOT NULL
);
CREATE INDEX idx_jobs_status ON jobs(status, priority DESC, id);

CREATE TABLE audit_log (
    id        INTEGER PRIMARY KEY AUTOINCREMENT,
    ts        INTEGER NOT NULL,
    action    TEXT NOT NULL,
    entity    TEXT,
    entity_id TEXT,
    details   TEXT
);
CREATE INDEX idx_audit_entity ON audit_log(entity, entity_id);

CREATE TABLE settings (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

-- Full-text index; rowid mirrors tracks.rowid. Maintained by library code.
CREATE VIRTUAL TABLE tracks_fts USING fts5(
    title, artist, version, remixer, album, label, genre, comment, notes, path,
    tokenize='unicode61 remove_diacritics 2'
);
